def campo(sig, alto, bajo):
    """Lee uo_out[alto:bajo] como entero, o None si todavia hay X."""
    s = str(sig.value)
    trozo = s[len(s) - 1 - alto : len(s) - bajo] if bajo else s[len(s) - 1 - alto :]
    return int(trozo, 2) if set(trozo) <= set("01") else None


@cocotb.test()
async def test_reconoce_un_siete(dut):
    dut._log.info("tt_um_canny78_f9_vic: Canny-78, reconocedor MNIST del 97,22 %")
    cocotb.start_soon(Clock(dut.clk, 100, units="ns").start())      # 10 MHz
    dut.ena.value = 1
    dut.ui_in.value = 0
    dut.uio_in.value = 0
    dut.rst_n.value = 0
    await ClockCycles(dut.clk, 8)
    dut.rst_n.value = 1
    await ClockCycles(dut.clk, 2)
    assert len(IMG) == 784, f"la imagen deberia tener 784 pixeles, tiene {len(IMG)}"

    for px in IMG + [0] * 8:                 # la imagen y la cola de 8 muestras
        dut.uio_in.value = 1                 # bit 0 = in_valid
        dut.ui_in.value = px
        await RisingEdge(dut.clk)
    dut.uio_in.value = 0
    for ciclos in range(1500):
        await RisingEdge(dut.clk)
        if campo(dut.uo_out, 5, 5) == 1:     # done
            break
    else:
        assert False, "no llego done en 1500 ciclos"
    await RisingEdge(dut.clk)
    digito = campo(dut.uo_out, 3, 0)
    valido = campo(dut.uo_out, 4, 4)
    dut._log.info(f"done tras {ciclos+1} ciclos: digito={digito} valido={valido}")
    assert valido == 1, "el chip se callo (valido=0) en vez de reconocer el 7"
    assert digito == 7, f"esperaba 7, contesto {digito}"
    dut._log.info("OK: Canny-78 reconocio el 7")
